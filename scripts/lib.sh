#!/usr/bin/env bash
# Shared guard rails for every automation entry point.
#
# Contract:
#   * TARGET defaults to "local". Nothing talks to real Azure unless TARGET=azure AND
#     CONFIRM_AZURE=<spoke subscription id> are both set explicitly.
#   * In local mode every subscription id MUST use the reserved all-zero prefix
#     00000000-0000-0000-0000-…, which no real Azure subscription uses, and the ARM
#     endpoint MUST be loopback/floci-az. Ambient ARM_*/AZURE_* credentials are scrubbed.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export ROOT
LOCAL_DIR="$ROOT/.local"
mkdir -p "$LOCAL_DIR"

TARGET="${TARGET:-local}"
export TARGET

log()  { printf '\033[1;34m[%s]\033[0m %s\n' "$(date +%H:%M:%S)" "$*" >&2; }
die()  { printf '\033[1;31m[FATAL]\033[0m %s\n' "$*" >&2; exit 1; }

LOCAL_SUB_RE='^00000000-0000-0000-0000-[0-9a-f]{12}$'

load_env() {
  case "$TARGET" in
    local)
      # Never let an operator's real Azure session leak into the emulator run (or vice versa).
      for v in $(env | grep -oE '^(ARM|AZURE)_[A-Z_]+' || true); do unset "$v"; done
      # shellcheck disable=SC1091
      [ -f "$ROOT/.env" ] && set -a && . "$ROOT/.env" && set +a
      # shellcheck disable=SC1091
      set -a; . "$ROOT/environments/local/local.env"; set +a
      ;;
    azure)
      [ -f "$ROOT/environments/azure/azure.env" ] || die "environments/azure/azure.env missing (copy azure.env.example)"
      # shellcheck disable=SC1091
      set -a; . "$ROOT/environments/azure/azure.env"; set +a
      ;;
    *) die "TARGET must be 'local' or 'azure' (got '$TARGET')" ;;
  esac
  guard_target
}

guard_target() {
  if [ "$TARGET" = local ]; then
    for s in HUB_SUBSCRIPTION_ID SPOKE_SUBSCRIPTION_ID; do
      [[ "${!s:-}" =~ $LOCAL_SUB_RE ]] || die "$s='${!s:-}' is not a reserved local id (00000000-0000-0000-0000-xxxxxxxxxxxx). Refusing."
    done
    [ "$HUB_SUBSCRIPTION_ID" != "$SPOKE_SUBSCRIPTION_ID" ] || die "hub and spoke subscription ids must differ"
    case "$FLOCI_METADATA_HOST" in
      localhost:*|127.0.0.1:*|floci-az:*) ;;
      *) die "FLOCI_METADATA_HOST=$FLOCI_METADATA_HOST is not a local emulator endpoint. Refusing." ;;
    esac
  else
    [ "${CONFIRM_AZURE:-}" = "${SPOKE_SUBSCRIPTION_ID:-unset}" ] \
      || die "Azure mode requires CONFIRM_AZURE=<spoke subscription id> (explicit opt-in)."
    [[ "$SPOKE_SUBSCRIPTION_ID" =~ $LOCAL_SUB_RE ]] && die "Azure mode with a local fixture subscription id."
    [ "$HUB_SUBSCRIPTION_ID" != "$SPOKE_SUBSCRIPTION_ID" ] || die "hub and spoke subscription ids must differ"
  fi
}

# Build a CA bundle (system roots + egress proxy CA if any + floci CA) without touching the OS store.
floci_trust() {
  [ "$TARGET" = local ] || return 0
  local crt="$LOCAL_DIR/floci-az.crt" bundle="$LOCAL_DIR/ca-bundle.pem"
  curl -sf "http://${FLOCI_DIRECT}/_floci/tls-cert" -o "$crt" \
    || die "floci-az is not answering on $FLOCI_DIRECT (run: make floci-up)"
  grep -q 'BEGIN CERTIFICATE' "$crt" || die "floci-az returned no certificate (is FLOCI_AZ_TLS_ENABLED=true?)"
  local base=""
  for base in "${SSL_CERT_FILE:-}" /root/.ccr/ca-bundle.crt /etc/ssl/certs/ca-certificates.crt /etc/ssl/cert.pem; do
    [ -n "$base" ] && [ -f "$base" ] && [ "$base" != "$bundle" ] && break
  done
  cat "$base" "$crt" > "$bundle"
  export SSL_CERT_FILE="$bundle"
}

# tf <stack> <subcommand> <args...>: one state boundary, isolated data dir + state file.
tf() {
  local stack="$1"; shift
  local dir="$ROOT/terraform/$stack"
  [ -d "$dir" ] || die "unknown stack $stack"
  export TF_DATA_DIR="$LOCAL_DIR/tfdata/$TARGET/${stack//\//_}"
  export TF_IN_AUTOMATION=1 CHECKPOINT_DISABLE=1
  [ -f "$LOCAL_DIR/terraformrc" ] || "$ROOT/scripts/provider-mirror.sh" >&2
  export TF_CLI_CONFIG_FILE="$LOCAL_DIR/terraformrc"
  local varfile="$ROOT/environments/$TARGET/${stack//\//_}.tfvars"
  local common="$ROOT/environments/$TARGET/common.tfvars"
  local sub="$1"; shift
  local vargs=()
  case "$sub" in plan|apply|destroy|refresh|import|console)
    # a saved plan file carries its own variables
    local last="${*: -1}"
    if [[ "$last" == -* || "$last" != *.tfplan ]]; then
      [ -f "$common" ] && vargs+=("-var-file=$common")
      [ -f "$varfile" ] && vargs+=("-var-file=$varfile")
      # generated by the hub team's onboarding step (hub-fixture.sh onboard-spoke)
      [ -f "$LOCAL_DIR/${stack//\//_}.generated.tfvars" ] && vargs+=("-var-file=$LOCAL_DIR/${stack//\//_}.generated.tfvars")
      vargs+=("-var=hub_subscription_id=$HUB_SUBSCRIPTION_ID" "-var=spoke_subscription_id=$SPOKE_SUBSCRIPTION_ID"
              "-var=tenant_id=$TENANT_ID" "-var=target=$TARGET")
      [ "$TARGET" = local ] && vargs+=("-var=floci_metadata_host=$FLOCI_METADATA_HOST")
    fi ;;
  esac
  if [ "$sub" = init ]; then
    rm -f "$dir/_backend_override.tf"
    if [ "$TARGET" = local ]; then
      mkdir -p "$LOCAL_DIR/state"
      vargs+=("-backend-config=path=$LOCAL_DIR/state/${stack//\//_}.tfstate" "-reconfigure")
    else
      printf 'terraform {\n  backend "azurerm" {}\n}\n' > "$dir/_backend_override.tf"
      vargs+=("-backend-config=$ROOT/environments/azure/${stack//\//_}.backend.hcl" "-reconfigure")
    fi
  fi
  (cd "$dir" && terraform "$sub" "${vargs[@]}" "$@")
}

floci() { curl -sf "http://${FLOCI_DIRECT}$1"; }

# Local-only secrets (generated, git-ignored). In Azure mode these come from the pipeline/Key Vault.
local_secrets() {
  [ "$TARGET" = local ] || return 0
  local d="$LOCAL_DIR/secrets"; mkdir -p "$d"; chmod 700 "$d"
  [ -f "$d/pg_admin_password" ] || printf 'L0cal-%s!' "$(head -c 18 /dev/urandom | base64 | tr -dc 'A-Za-z0-9')" > "$d/pg_admin_password"
  if [ ! -f "$d/id_ed25519.pub" ]; then
    if command -v ssh-keygen >/dev/null; then
      ssh-keygen -q -t ed25519 -N '' -C sas-viya-local -f "$d/id_ed25519"
    else
      python3 "$ROOT/scripts/gen-ssh-key.py" "$d/id_ed25519"
    fi
  fi
  export TF_VAR_postgres_admin_password TF_VAR_ssh_public_key
  TF_VAR_postgres_admin_password="$(cat "$d/pg_admin_password")"
  TF_VAR_ssh_public_key="$(cat "$d/id_ed25519.pub")"
}
